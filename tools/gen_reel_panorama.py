#!/usr/bin/env python3
"""Generate the repeated Reel markup in banner.xml and the reel theme rules in hud.vcss.

Usage: gen_reel_panorama.py          rewrite the generated blocks
       gen_reel_panorama.py --check  exit 1 if a generated block is out of date
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "workshop" / "content" / "panorama"
BANNER_XML = CONTENT / "layout" / "custom_game" / "rollthedice" / "banner.xml"
HUD_VCSS = CONTENT / "styles" / "custom_game" / "rollthedice" / "hud.vcss"

# Keep in sync with Reel.RowCount / Reel.WinRow (validated by validate_panorama.py).
ROW_COUNT = 22
WIN_ROW = 20
ROW_ID_PREFIX = "ReelRow"
FILLER_VAR_PREFIX = "rr_f"
WIN_VAR = "rr_win"

# name -> accent hex (rainbow order; keep in sync with HudTheme / validate_panorama.py).
THEMES: list[tuple[str, str]] = [
    ("red", "#e05a5a"),
    ("coral", "#ff7a59"),
    ("orange", "#ff8a3d"),
    ("copper", "#e08a5a"),
    ("gold", "#f0a531"),
    ("t", "#eabe54"),
    ("lime", "#c6f04a"),
    ("green", "#6fdc78"),
    ("teal", "#2ec9a6"),
    ("cyan", "#3ee0f0"),
    ("blue", "#5b8cff"),
    ("ct", "#96c8fa"),
    ("purple", "#b07cff"),
    ("magenta", "#e85dff"),
    ("pink", "#ff6b9a"),
    ("silver", "#c9d2dc"),
]

XML_BLOCK = re.compile(
    r"(?P<indent>[ \t]*)<!-- reel rows: generated by tools/gen_reel_panorama.py - do not edit by hand -->\n"
    r".*?"
    r"[ \t]*<!-- /reel rows -->",
    re.S,
)
CSS_BLOCK = re.compile(
    r"/\* reel themes: generated by tools/gen_reel_panorama\.py - do not edit by hand \*/\n"
    r".*?"
    r"/\* /reel themes \*/",
    re.S,
)


def light(accent: str, amount: float = 0.45) -> str:
    value = int(accent[1:], 16)
    channels = [(value >> 16) & 255, (value >> 8) & 255, value & 255]
    return "#" + "".join(f"{round(c + (255 - c) * amount):02x}" for c in channels)


def rows_xml(indent: str) -> str:
    lines = [f"{indent}<!-- reel rows: generated by tools/gen_reel_panorama.py - do not edit by hand -->"]
    for i in range(ROW_COUNT):
        if i == WIN_ROW:
            lines.append(f'{indent}<Panel class="RrRow RrWinRow" hittest="false">')
            var = WIN_VAR
        else:
            lines.append(f'{indent}<Panel id="{ROW_ID_PREFIX}{i}" class="RrRow tone-neutral" hittest="false">')
            var = f"{FILLER_VAR_PREFIX}{i}"
        lines.append(f'{indent}\t<Panel class="RrStripe" hittest="false" />')
        lines.append(f'{indent}\t<Panel class="RrSym" hittest="false">')
        lines.append(f'{indent}\t\t<Panel class="RrSymBox" hittest="false">')
        lines.append(f'{indent}\t\t\t<Panel class="RrSymTip" hittest="false" />')
        lines.append(f"{indent}\t\t</Panel>")
        lines.append(f"{indent}\t</Panel>")
        lines.append(f'{indent}\t<Label class="RrName stratum-bold-tf" hittest="false" text="{{s:{var}}}" />')
        lines.append(f"{indent}</Panel>")
    lines.append(f"{indent}<!-- /reel rows -->")
    return "\n".join(lines)


def themes_css() -> str:
    lines = ["/* reel themes: generated by tools/gen_reel_panorama.py - do not edit by hand */"]
    for name, accent in THEMES:
        sel = f".Reel.theme-{name}"
        lines.append(f"{sel} .RrArrowTip, {sel} .RrDrain {{ background-color: {accent}; }}")
        lines.append(f"{sel} .RrRim {{ border-color: {accent}66; }}")
        lines.append(f"{sel} .RrWinLine {{ border-color: {accent}aa; background-color: {accent}14; }}")
        lines.append(f"{sel}.is-stopped .RrWinLine {{ background-color: {accent}33; box-shadow: {accent}55 0px 0px 18px 0px; }}")
        lines.append(f"{sel}.is-stopped Label.RrTitle {{ color: {light(accent)}; }}")
    lines.append("/* /reel themes */")
    return "\n".join(lines)


def render() -> dict[Path, str]:
    xml = BANNER_XML.read_text(encoding="utf-8")
    match = XML_BLOCK.search(xml)
    if not match:
        raise SystemExit(f"ERROR: {BANNER_XML.name}: reel rows markers not found")
    xml = xml[: match.start()] + rows_xml(match.group("indent")) + xml[match.end():]

    css = HUD_VCSS.read_text(encoding="utf-8")
    if not CSS_BLOCK.search(css):
        raise SystemExit(f"ERROR: {HUD_VCSS.name}: reel themes markers not found")
    css = CSS_BLOCK.sub(lambda _: themes_css(), css, count=1)
    return {BANNER_XML: xml, HUD_VCSS: css}


def main() -> None:
    check = "--check" in sys.argv[1:]
    stale = []
    for path, text in render().items():
        if path.read_text(encoding="utf-8") == text:
            continue
        if check:
            stale.append(path.name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print(f"ERROR: generated reel blocks out of date in {', '.join(stale)} - run tools/gen_reel_panorama.py", file=sys.stderr)
        raise SystemExit(1)


if __name__ == "__main__":
    main()
