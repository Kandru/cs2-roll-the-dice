#!/usr/bin/env python3
"""Generate the info menu layout (info_v3.xml) and its theme rules in info_v3.vcss.

The whole layout is generated: the row, tab, language and filter pools must match InfoMenuIds.cs
(validated by validate_panorama.py), and hand-copied pool markup drifts.

Usage: gen_info_panorama.py          rewrite the generated files/blocks
       gen_info_panorama.py --check  exit 1 if something is out of date
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "workshop" / "content" / "panorama"
INFO_XML = CONTENT / "layout" / "custom_game" / "rollthedice" / "info_v3.xml"
INFO_VCSS = CONTENT / "styles" / "custom_game" / "rollthedice" / "info_v3.vcss"

# Keep in sync with InfoMenuIds (validated by validate_panorama.py).
ROWS = 64
TABS = 5
LANGUAGES = 2
FILTERS = 4
ROOT_ID = "ri-root"
TAB_ID_PREFIX = "ri-tab-"
LANG_ID_PREFIX = "ri-lang-"
ROW_ID_PREFIX = "ri-row-"
FILTER_ID_PREFIX = "ri-flt-"
# round view: one column per team, each with its own row pool
TEAM_ROWS = 32
TEAMS: list[tuple[str, str]] = [("ct", "ri-ctr-"), ("t", "ri-tr-")]  # (key, row id prefix); vars ri_<key>r<n>_a / _c

# name -> accent hex (rainbow order; keep in sync with HudTheme / validate_panorama.py).
THEMES: list[tuple[str, str]] = [
    ("red", "#e05a5a"),
    ("coral", "#ff7a59"),
    ("orange", "#ff8a3d"),
    ("copper", "#e08a5a"),
    ("gold", "#f0a531"),
    ("t", "#eabe54"),
    ("lime", "#c6f04a"),
    ("green", "#6fdc78"),
    ("teal", "#2ec9a6"),
    ("cyan", "#3ee0f0"),
    ("blue", "#5b8cff"),
    ("ct", "#96c8fa"),
    ("purple", "#b07cff"),
    ("magenta", "#e85dff"),
    ("pink", "#ff6b9a"),
    ("silver", "#c9d2dc"),
]

CSS_BLOCK = re.compile(
    r"/\* info themes: generated by tools/gen_info_panorama\.py - do not edit by hand \*/\n"
    r".*?"
    r"/\* /info themes \*/",
    re.S,
)


def row_xml(i: int) -> list[str]:
    return [
        f'<Panel id="{ROW_ID_PREFIX}{i}" class="RiRow tone-none team-none is-off" hittest="false">',
        '\t<Panel class="RiIdx" hittest="false">',
        f'\t\t<Label class="RiIdxLabel stratum-bold-tf" hittest="false" text="{{s:ri_r{i}_i}}" />',
        "\t</Panel>",
        '\t<Panel class="RiMark" hittest="false">',
        '\t\t<Panel class="RiMarkBox" hittest="false">',
        '\t\t\t<Panel class="RiMarkTip" hittest="false" />',
        "\t\t</Panel>",
        "\t</Panel>",
        f'\t<Label class="RiRowTitle stratum-bold-tf" hittest="false" text="{{s:ri_r{i}_a}}" />',
        f'\t<Label class="RiRowDesc stratum-medium-tf" hittest="false" text="{{s:ri_r{i}_c}}" />',
        f'\t<Label class="RiRowMeta stratum-bold-tf" hittest="false" text="{{s:ri_r{i}_b}}" />',
        "</Panel>",
    ]


def team_row_xml(key: str, prefix: str, i: int) -> list[str]:
    return [
        f'<Panel id="{prefix}{i}" class="RiTeamRow tone-none is-off" hittest="false">',
        '\t<Panel class="RiMark" hittest="false">',
        '\t\t<Panel class="RiMarkBox" hittest="false">',
        '\t\t\t<Panel class="RiMarkTip" hittest="false" />',
        "\t\t</Panel>",
        "\t</Panel>",
        f'\t<Label class="RiTeamName stratum-bold-tf" hittest="false" text="{{s:ri_{key}r{i}_a}}" />',
        f'\t<Label class="RiTeamDice stratum-medium-tf" hittest="false" text="{{s:ri_{key}r{i}_c}}" />',
        "</Panel>",
    ]


def team_column_xml(key: str, prefix: str) -> list[str]:
    rows = [line for i in range(TEAM_ROWS) for line in team_row_xml(key, prefix, i)]
    return [
        f'<Panel class="RiTeamCol RiTeamCol{key.upper()}" hittest="false">',
        '\t<Panel class="RiTeamHead" hittest="false">',
        f'\t\t<Label class="RiTeamTitle stratum-bold-tf" hittest="false" text="{{s:ri_{key}_h}}" />',
        f'\t\t<Label class="RiTeamCount stratum-bold-tf" hittest="false" text="{{s:ri_{key}_n}}" />',
        "\t</Panel>",
        '\t<Panel class="RiTeamList" hittest="false">',
        *indent(rows, 2),
        f'\t\t<Label id="ri-{key}-empty" class="RiTeamEmpty stratum-medium-tf is-off" hittest="false" text="{{s:ri_{key}_empty}}" />',
        "\t</Panel>",
        "</Panel>",
    ]


def tab_xml(i: int) -> list[str]:
    active = " is-active" if i == 0 else ""
    return [
        f'<Button id="{TAB_ID_PREFIX}{i}" class="RiNav{active}">',
        f'\t<Label class="RiNavLabel stratum-bold-tf" hittest="false" text="{{s:ri_t{i}}}" />',
        f'\t<Label class="RiNavCount stratum-bold-tf" hittest="false" text="{{s:ri_tc{i}}}" />',
        "</Button>",
    ]


def chip_xml(panel_id: str, var: str, extra: str = "") -> list[str]:
    return [
        f'<Button id="{panel_id}" class="RiChip{extra}">',
        f'\t<Label class="RiChipLabel stratum-bold-tf" hittest="false" text="{{s:{var}}}" />',
        "</Button>",
    ]


def lang_xml(i: int) -> list[str]:
    return [
        f'<Button id="{LANG_ID_PREFIX}{i}" class="RiLang">',
        f'\t<Label class="RiLangLabel stratum-bold-tf" hittest="false" text="{{s:ri_l{i}}}" />',
        "</Button>",
    ]


def indent(lines: list[str], depth: int) -> list[str]:
    pad = "\t" * depth
    return [pad + line for line in lines]


