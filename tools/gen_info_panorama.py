def themes_css() -> str:
    lines = ["/* info themes: generated by tools/gen_info_panorama.py - do not edit by hand */"]
    for name, accent in THEMES:
        sel = f".RiCard.theme-{name}"
        lines.append(f"{sel} .RiCorner {{ border-color: {accent}; }}")
        lines.append(f"{sel} Label.RiKicker, {sel} Label.RiIdxLabel, {sel} .RiNav.is-active Label.RiNavCount, {sel} Label.RiCount {{ color: {accent}; }}")
        lines.append(f"{sel} .RiIdx {{ border-color: {accent}; }}")
        lines.append(f"{sel} .RiNav.is-active {{ background-color: {accent}1f; border-left: 3px solid {accent}; }}")
        lines.append(f"{sel} .RiChip.is-active, {sel} .RiLang.is-active, {sel} .RiRow.is-self, {sel} .RiTeamRow.is-self, {sel} .RiSearch {{ background-color: {accent}1f; border: 1px solid {accent}; }}")
        lines.append(f"{sel} .RiChip:hover, {sel} .RiLang:hover {{ border: 1px solid {accent}66; }}")
        lines.append(f"{sel} .RiSwitch.is-on .RiSwitchTrack {{ background-color: {accent}33; border: 1px solid {accent}; }}")
        lines.append(f"{sel} .RiSwitch.is-on .RiSwitchKnob {{ background-color: {accent}; }}")
        lines.append(f"{sel} .RiSwitch.is-on Label.RiSwitchState {{ color: {accent}; }}")
    lines.append("/* /info themes */")
    return "\n".join(lines)


def render() -> dict[Path, str]:
    css = INFO_VCSS.read_text(encoding="utf-8")
    if not CSS_BLOCK.search(css):
        raise SystemExit(f"ERROR: {INFO_VCSS.name}: info themes markers not found")
    css = CSS_BLOCK.sub(lambda _: themes_css(), css, count=1)
    return {INFO_XML: layout_xml(), INFO_VCSS: css}


def main() -> None:
    check = "--check" in sys.argv[1:]
    stale = []
    for path, text in render().items():
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        if check:
            stale.append(path.name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print(f"ERROR: generated info menu out of date in {', '.join(stale)} - run tools/gen_info_panorama.py", file=sys.stderr)
        raise SystemExit(1)


if __name__ == "__main__":
    main()
